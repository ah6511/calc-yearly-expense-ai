import os, csv
import asyncio

from ExpenseAI.ExtractTransactionsAgent import ExtractTransactionsAgent
from Utils.utils import save_to_s3, list_pdfs_in_s3, download_pdf_from_s3, list_pdfs_in_local_dir, save_to_local_dir
from ExpenseAI.Models import Transaction, CategorizedTransaction

async def calc_monthly_expense(pdf_path: str) -> tuple[float, list]:
    agent = ExtractTransactionsAgent()
    result = await asyncio.to_thread(agent.run, pdf_path)
    withdrawals_sum = result["transactions_sum"]    
    arr = pdf_path.split("/")
    month = arr[-1][4:6]
    print(f"Expense for month {month} is {withdrawals_sum}.")
    return withdrawals_sum, result["transactions"]

async def calc_expenses(pdf_directory: str) -> tuple[float, list[CategorizedTransaction]]:
    tasks = []
    if os.getenv("LOCAL_MODE", "false").lower() == "true":
        for filename in os.listdir(pdf_directory):
            if filename.lower().endswith(".pdf"):
                pdf_path = os.path.join(pdf_directory, filename)
                tasks.append(calc_monthly_expense(pdf_path))
                print(f"Processing file: {filename}")
    else:
        pdfs = list_pdfs_in_local_dir('pdf') if os.getenv("USE_LOCAL", "false").lower() == "true" else list_pdfs_in_s3("pdfs") 
        for pdf in pdfs:
            filename = pdf.split("/")[-1]
            if os.getenv("USE_LOCAL", "false").lower() == "false":
                pdf_path =  "/tmp/" + filename
                download_pdf_from_s3(pdf, pdf_path)
            else:
                pdf_path = pdf
            tasks.append(calc_monthly_expense(pdf_path))
            print(f"Processing file: {filename}")
    
    results = await asyncio.gather(*tasks)
    total_sum: float = sum(withdrawals_sum for withdrawals_sum, _ in results)
    withdrawals: list[CategorizedTransaction] = [tx for _, tx_list in results for tx in tx_list]
    withdrawals.sort(key=lambda withdrawal: withdrawal["date"])

    print(f"The number of withdrawals for the year: {len(withdrawals)}")
    print(f"Total sum of withdrawals for the year: {total_sum}")

    if os.getenv("LOCAL_MODE", "false").lower() == "true":
        total_withdrawals_path = os.path.join(os.getcwd(), "transactions", "total_withdrawals.csv")
        with open(total_withdrawals_path, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=withdrawals[0].keys())
            writer.writeheader()
            writer.writerows(withdrawals)  # Generated by Copilot
    else:
        text = ",".join(withdrawals[0].keys())
        for withdrawal in withdrawals:
            row = ",".join([str(value) for value in withdrawal.values()])
            text += "\n" + row
        save_to_local_dir(text, os.path.join(os.getcwd(), "transactions"), "total_withdrawals.csv") if os.getenv("USE_LOCAL", "false").lower() == "true" else save_to_s3(text, "transactions", "total_withdrawals.csv")

    return total_sum, withdrawals

